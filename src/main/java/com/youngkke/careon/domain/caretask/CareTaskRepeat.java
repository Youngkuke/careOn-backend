package com.youngkke.careon.domain.caretask;

/**
 * 반복 규칙.
 *
 * <p>"오늘의 할 일"을 주는 API는 반복 개념을 전제한다. 매일 19시 복약처럼 되풀이되는 항목을 보호자가 매일
 * 새로 등록하게 할 수는 없기 때문이다.
 *
 * <p>WEEKLY가 필요한 이유는 돌봄 일정 상당수가 요일제이기 때문이다. 투석은 주 3회 요일 고정이 사실상
 * 표준이고, 물리치료·방문요양도 주 2~3회 지정 요일이다. 주간보호센터는 평일만 다니므로 DAILY로 등록하면
 * 가지 않는 주말에도 워치가 울린다.
 */
public enum CareTaskRepeat {
    /** 지정한 날짜 하루만. */
    ONCE,
    /** 매일 같은 시각에. */
    DAILY,
    /** 지정한 요일마다 같은 시각에. */
    WEEKLY
}
